export function get15MinQuote(): string {
  // 15 minutes in milliseconds = 15 * 60 * 1000 = 900000
  const intervalIndex = Math.floor(Date.now() / (15 * 60 * 1000));
  const index = Math.abs(intervalIndex) % TRADING_QUOTES.length;
  return TRADING_QUOTES[index];
}

export function getDailyQuote(): string {
  return get15MinQuote();
}
